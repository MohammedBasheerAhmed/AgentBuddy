// Control-to-test traceability: which test enforces which claim of the security review. Pure (texts and the list of test files in;
// rows and Markdown out), used by scripts/traceability.js and tests/reviewpack.test.js.

/** Every `tests/...` path named in backticks in a Markdown text, in order, without repeats. Globs (`tests/pii-*.test.js`) are kept. */
function testRefs(text) {
  return [...new Set([...String(text).matchAll(/`(tests\/[A-Za-z0-9_.*\-/]+)`/g)].map((m) => m[1]))];
}

/** The test files a reference stands for (a glob may stand for several); [] when none exists. */
function expandRef(ref, testFiles) {
  if (!ref.includes('*')) return testFiles.includes(ref) ? [ref] : [];
  const re = new RegExp(`^${ref.split('*').map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('[^/]*')}$`);
  return testFiles.filter((f) => re.test(f));
}

/** References that name no existing test file. */
function missingRefs(text, testFiles) {
  return testRefs(text).filter((ref) => !expandRef(ref, testFiles).length);
}

const cells = (line) =>
  line
    .trim()
    .replace(/^\|/, '')
    .replace(/\|$/, '')
    .split(/(?<!\\)\|/)
    .map((c) => c.trim());

/** The rows of the first Markdown table after the heading that matches `heading`, as objects keyed by the header cells. */
function tableAfter(text, heading) {
  const lines = String(text).split(/\r?\n/);
  const start = lines.findIndex((l) => /^#{1,6}\s/.test(l) && heading.test(l));
  if (start < 0) return [];
  let i = start + 1;
  while (i < lines.length && !lines[i].trim().startsWith('|')) {
    if (/^#{1,6}\s/.test(lines[i])) return [];
    i += 1;
  }
  const header = cells(lines[i] || '');
  const rows = [];
  for (i += 2; i < lines.length && lines[i].trim().startsWith('|'); i += 1) {
    const c = cells(lines[i]);
    rows.push(Object.fromEntries(header.map((h, k) => [h, c[k] || ''])));
  }
  return rows;
}

// The first sentence of a cell, without Markdown emphasis or code marks (a cut inside a code span would break the table).
const firstSentence = (text) => {
  const plain = String(text).replace(/\*\*|`/g, '').trim();
  const m = /^(.{10,200}?\.)(\s|$)/.exec(plain);
  if (m) return m[1];
  return plain.length <= 200 ? plain : `${plain.slice(0, plain.lastIndexOf(' ', 200))} ...`;
};

/**
 * The matrix: one row per control of docs/security.md section 4 and per threat of docs/review-pack/stride.md.
 * @returns {{ source: string, id: string, claim: string, refs: string[], files: string[], missing: string[] }[]}
 */
function buildMatrix({ security, stride }, testFiles) {
  const row = (source, id, claim, testCell) => {
    const refs = testRefs(testCell);
    const files = [...new Set(refs.flatMap((r) => expandRef(r, testFiles)))];
    return { source, id, claim, refs, files, missing: refs.filter((r) => !expandRef(r, testFiles).length), other: refs.length ? '' : String(testCell).replace(/`/g, '') };
  };
  const controls = tableAfter(security, /^##\s*4\.\s*Controls/i).map((r) => row('security.md 4', r.Concern, firstSentence(r.Control), r.Test));
  const threats = tableAfter(stride, /STRIDE/i).map((r) => row('stride.md', r.ID, r.Threat, r.Test));
  return [...controls, ...threats];
}

function renderMatrix(rows) {
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const lines = [
    '# Control-to-test traceability',
    '',
    'Generated by `node scripts/traceability.js` from `docs/security.md` (section 4) and `docs/review-pack/stride.md`. Do not edit by',
    'hand: change those files and run the script again (`npm run traceability`). `--check` fails when a named test file does not exist',
    'or when this file is out of date.',
    '',
    '| Source | Control or threat | Claim | Test files | Status |',
    '|---|---|---|---|---|',
  ];
  for (const r of rows) {
    const tests = r.files.length ? r.files.map((f) => `\`${f}\``).join(', ') : r.other || 'none named';
    const status = r.missing.length ? `MISSING: ${r.missing.join(', ')}` : r.files.length ? 'ok' : 'no automated test';
    lines.push(`| ${esc(r.source)} | ${esc(r.id)} | ${esc(r.claim)} | ${esc(tests)} | ${esc(status)} |`);
  }
  const named = new Set(rows.flatMap((r) => r.files));
  lines.push('', `${rows.length} rows; ${named.size} distinct test files named; ${rows.filter((r) => r.missing.length).length} rows name a missing file.`, '');
  return lines.join('\n');
}

module.exports = { testRefs, expandRef, missingRefs, tableAfter, buildMatrix, renderMatrix };
